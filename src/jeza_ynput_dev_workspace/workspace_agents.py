#!/usr/bin/env python

"""Turn provider-neutral subagent definitions into harness files — ``agents``.

Definitions live in ``config/agents/<name>.md`` and name a tier (``light``,
``standard``, ``deep``), never a model. ``config/agents.json`` maps each
tier to a model and a thinking effort per provider; switching provider is
one line there. ``sync`` writes the active provider's own files (Claude
Code: ``.claude/agents/<name>.md``). Those are generated and gitignored, so
every machine runs ``sync`` once (``bootstrap`` does) and ``doctor`` reports
drift. See docs/subagents.md.

Script usage:
  uv run ayon-workspace agents list [--provider NAME]
  uv run ayon-workspace agents tier TIER [--provider NAME]
  uv run ayon-workspace agents sync [--check] [--provider NAME]
"""

import json
import logging
import re
from pathlib import Path
from typing import Dict, List, Tuple

import click

from .workspace_common import resolve_workspace_root

DEFINITIONS_DIR = Path("config") / "agents"
CONFIG_FILE = Path("config") / "agents.json"

# Used when config/agents.json is missing or leaves a value out.
DEFAULTS = {
    "provider": "claude",
    "providers": {
        "claude": {
            "light": {"model": "haiku", "effort": "low"},
            "standard": {"model": "sonnet", "effort": "medium"},
            "deep": {"model": "opus", "effort": "high"},
        }
    },
}

# Where each provider reads subagent files, relative to the workspace root.
# A provider missing here has no writer yet: ``sync`` refuses it.
OUTPUT_DIRS = {"claude": Path(".claude") / "agents"}

# First line of every generated body; marks files ``sync`` may remove.
GENERATED_MARK = "<!-- generated by `uv run ayon-workspace agents sync`"

FRONTMATTER = re.compile(r"---\n(.*?)\n---\n(.*)", re.DOTALL)


def _merge(base: dict, override: dict) -> dict:
    """Return ``base`` updated recursively with ``override``."""
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def load_config(root: Path) -> dict:
    """Load ``config/agents.json`` over the built-in defaults.

    Args:
        root (Path): resolved workspace root.

    Returns:
        dict: ``provider`` (the active one) and ``providers`` (tier ->
            model and effort, per provider).
    """
    path = root / CONFIG_FILE
    override = json.loads(path.read_text()) if path.is_file() else {}
    return _merge(DEFAULTS, override)


def resolve_tier(tier: str, provider: str, config: dict) -> Dict[str, str]:
    """Return the model and effort a tier gets on a provider.

    Args:
        tier (str): ``light``, ``standard`` or ``deep``.
        provider (str): provider name, a key of ``providers``.
        config (dict): result of ``load_config``.

    Returns:
        Dict[str, str]: ``provider``, ``tier``, ``model`` and, when the
            provider has one, ``effort``.

    Raises:
        click.ClickException: if the provider has no model for the tier.
    """
    try:
        mapping = config["providers"][provider][tier]
    except KeyError:
        message = (
            f"No model for tier '{tier}' on provider '{provider}' — add it "
            f"to {CONFIG_FILE}."
        )
        raise click.ClickException(message) from None
    return {"provider": provider, "tier": tier, **mapping}


def read_definitions(root: Path) -> List[Tuple[Dict[str, str], str]]:
    """Read every definition in ``config/agents/``, sorted by file name.

    Args:
        root (Path): resolved workspace root.

    Returns:
        List[Tuple[Dict[str, str], str]]: frontmatter fields and body of
            each definition.

    Raises:
        click.ClickException: if a definition has no frontmatter, or lacks
            ``name``, ``description`` or ``tier``.
    """
    definitions = []
    for path in sorted((root / DEFINITIONS_DIR).glob("*.md")):
        match = FRONTMATTER.match(path.read_text())
        if not match:
            message = f"{path} has no frontmatter"
            raise click.ClickException(message)
        meta = {}
        for line in match.group(1).splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip()
        missing = {"name", "description", "tier"} - set(meta)
        if missing:
            message = f"{path} lacks {', '.join(sorted(missing))}"
            raise click.ClickException(message)
        definitions.append((meta, match.group(2)))
    return definitions


def render_definition(
    meta: Dict[str, str], body: str, provider: str, config: dict
) -> str:
    """Render one definition as the provider's subagent file.

    Args:
        meta (Dict[str, str]): the definition's frontmatter fields.
        body (str): the definition's instructions.
        provider (str): provider to render for.
        config (dict): result of ``load_config``.

    Returns:
        str: the file content, frontmatter with the tier's model first.
    """
    resolved = resolve_tier(meta["tier"], provider, config)
    head = [
        f"name: {meta['name']}",
        f"description: {meta['description']}",
        f"model: {resolved['model']}",
    ]
    if resolved.get("effort"):
        head.append(f"effort: {resolved['effort']}")
    if meta.get("tools"):
        head.append(f"tools: {meta['tools']}")
    note = (
        f"{GENERATED_MARK} from config/agents/{meta['name']}.md "
        f"(tier {resolved['tier']}); edit that -->"
    )
    return "---\n" + "\n".join(head) + "\n---\n" + note + "\n" + body


def plan_sync(
    root: Path, provider: str, config: dict
) -> Tuple[Dict[Path, str], List[Path]]:
    """Return what ``sync`` would change, without writing anything.

    Args:
        root (Path): resolved workspace root.
        provider (str): provider to sync for.
        config (dict): result of ``load_config``.

    Returns:
        Tuple[Dict[Path, str], List[Path]]: files to write (missing or out
            of date) with their content, and generated files whose
            definition is gone.

    Raises:
        click.ClickException: if the provider has no file writer yet.
    """
    if provider not in OUTPUT_DIRS:
        message = (
            f"No file writer for provider '{provider}' yet — add one in "
            f"workspace_agents.py (OUTPUT_DIRS, render_definition)."
        )
        raise click.ClickException(message)
    out_dir = root / OUTPUT_DIRS[provider]
    writes = {}
    expected = set()
    for meta, body in read_definitions(root):
        dest = out_dir / f"{meta['name']}.md"
        expected.add(dest)
        text = render_definition(meta, body, provider, config)
        if not dest.is_file() or dest.read_text() != text:
            writes[dest] = text
    stale = [
        path
        for path in sorted(out_dir.glob("*.md"))
        if path not in expected and GENERATED_MARK in path.read_text()
    ]
    return writes, stale


def sync_agents(
    root: Path, provider: str, dry_run: bool, log: logging.Logger
) -> None:
    """Write a provider's subagent files; remove the stale ones.

    Args:
        root (Path): resolved workspace root.
        provider (str): provider to sync for; empty means the active one.
        dry_run (bool): if set, only log what would change.
        log (logging.Logger): logger to report progress on.
    """
    config = load_config(root)
    provider = provider or config["provider"]
    writes, stale = plan_sync(root, provider, config)
    prefix = "[dry-run] would " if dry_run else ""
    for dest, text in writes.items():
        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text)
        log.info(f"{prefix}write {dest.relative_to(root)}")
    for path in stale:
        if not dry_run:
            path.unlink()
        log.info(f"{prefix}remove {path.relative_to(root)} (no definition)")
    if not writes and not stale:
        log.info(f"agents: {OUTPUT_DIRS[provider]} is up to date")


def check_agents(
    root: Path, log: logging.Logger, provider: str = ""
) -> List[str]:
    """Return drift messages for the generated subagent files (``doctor``).

    Args:
        root (Path): resolved workspace root.
        log (logging.Logger): logger for informational notes.
        provider (str): provider to check; empty means the active one.

    Returns:
        List[str]: one message per file ``sync`` would change; empty means
            clean, or a provider with no file writer to check.
    """
    config = load_config(root)
    provider = provider or config["provider"]
    if provider not in OUTPUT_DIRS:
        log.info(f"agents: no file writer for '{provider}', skipping")
        return []
    try:
        writes, stale = plan_sync(root, provider, config)
    except click.ClickException as exc:
        return [f"agents: {exc.message}"]
    fix = "run `uv run ayon-workspace agents sync`"
    problems = [
        f"{dest.relative_to(root)} is missing or out of date — {fix}"
        for dest in writes
    ]
    problems += [
        f"{path.relative_to(root)} has no definition left — {fix}"
        for path in stale
    ]
    if not problems:
        log.info(f"agents: {OUTPUT_DIRS[provider]} matches {DEFINITIONS_DIR}")
    return problems


provider_option = click.option(
    "--provider",
    default="",
    help="Provider to use (default: the one config/agents.json names).",
)


@click.group(name="agents")
def agents() -> None:
    """Subagent definitions and their tiers (see docs/subagents.md)."""


@agents.command(name="list")
@provider_option
def list_agents(provider: str) -> None:
    """Show each definition with its tier and the model it gets now."""
    root = resolve_workspace_root()
    config = load_config(root)
    provider = provider or config["provider"]
    for meta, _body in read_definitions(root):
        resolved = resolve_tier(meta["tier"], provider, config)
        effort = resolved.get("effort", "-")
        click.echo(
            f"{meta['name']:<20}{resolved['tier']:<10}"
            f"{resolved['model']} / {effort}"
        )


@agents.command(name="tier")
@click.argument("tier_name", metavar="TIER")
@provider_option
def tier(tier_name: str, provider: str) -> None:
    """Print the model and effort of TIER as JSON."""
    config = load_config(resolve_workspace_root())
    provider = provider or config["provider"]
    click.echo(json.dumps(resolve_tier(tier_name, provider, config)))


@agents.command(name="sync")
@click.option(
    "--check", is_flag=True, help="Only report drift; exit 1 if there is any."
)
@provider_option
def sync(check: bool, provider: str) -> None:
    """Write the provider's subagent files from config/agents/.

    Raises:
        SystemExit: with code 1 if ``--check`` finds drift.
    """
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    log = logging.getLogger("agents")

    root = resolve_workspace_root()
    if not check:
        sync_agents(root, provider, dry_run=False, log=log)
        return

    problems = check_agents(root, log, provider)
    for problem in problems:
        log.info(problem)
    if problems:
        raise SystemExit(1)


if __name__ == "__main__":
    agents()
