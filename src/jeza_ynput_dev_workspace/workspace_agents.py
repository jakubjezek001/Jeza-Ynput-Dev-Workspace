#!/usr/bin/env python

"""Project the universal ``.agents/`` subagents into each harness — ``agents``.

The committed source of every subagent is ``.agents/agents/<name>.md``:
frontmatter ``name``, ``description``, ``tier`` (``light``, ``standard``,
``deep``) and ``tools``, then the instructions. A harness that reads
``.agents/agents/`` uses those files as they are. The others only read their
own folder, so ``sync`` writes a copy in each harness's format, with the
model and effort ``.agents/tiers.json`` maps the tier to on that harness.
The copies are generated and gitignored: every machine runs ``sync`` once
(``bootstrap`` does) and ``doctor`` reports drift. See docs/subagents.md.

Script usage:
  uv run ayon-workspace agents list [--harness NAME]
  uv run ayon-workspace agents tier TIER [--harness NAME]
  uv run ayon-workspace agents sync [--check] [--harness NAME]
"""

import json
import logging
import re
from pathlib import Path
from typing import Dict, List, Tuple

import click

from .workspace_common import resolve_workspace_root

AGENTS_DIR = Path(".agents") / "agents"
TIERS_FILE = Path(".agents") / "tiers.json"

# Used when .agents/tiers.json is missing or leaves a value out. A tier with
# no model inherits the model of the session that delegates to it.
DEFAULTS = {
    "targets": [
        "claude",
        "cursor",
        "codex",
        "gemini",
        "opencode",
        "copilot",
    ],
    "tiers": {"light": "", "standard": "", "deep": ""},
    "harnesses": {
        "claude": {
            "light": {"model": "haiku", "effort": "low"},
            "standard": {"model": "sonnet", "effort": "medium"},
            "deep": {"model": "opus", "effort": "high"},
        },
    },
}

# Present in every generated file; marks the files ``sync`` may remove.
GENERATED_MARK = "generated by `uv run ayon-workspace agents sync`"

FRONTMATTER = re.compile(r"---\n(.*?)\n---\n(.*)", re.DOTALL)


def _merge(base: dict, override: dict) -> dict:
    """Return ``base`` updated recursively with ``override``."""
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def _quote(value: str) -> str:
    """Return ``value`` quoted as a valid YAML and TOML string."""
    return json.dumps(value, ensure_ascii=False)


def _is_readonly(meta: Dict[str, str]) -> bool:
    """Return whether a definition's ``tools`` leave out file edits."""
    if not meta.get("tools"):
        return False
    tools = {tool.strip() for tool in meta["tools"].split(",")}
    return not tools & {"Edit", "Write"}


def _markdown(lines: List[str], meta: Dict[str, str], body: str) -> str:
    """Return frontmatter lines, the generated note and the body."""
    note = (
        f"<!-- {GENERATED_MARK} from {AGENTS_DIR.as_posix()}/"
        f"{meta['name']}.md (tier {meta['tier']}); edit that -->"
    )
    return "---\n" + "\n".join(lines) + "\n---\n" + note + "\n" + body


def _render_claude(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the Claude Code copy: model, effort, tool allowlist."""
    lines = [f"name: {meta['name']}"]
    lines.append(f"description: {_quote(meta['description'])}")
    if mapping.get("model"):
        lines.append(f"model: {mapping['model']}")
    if mapping.get("effort"):
        lines.append(f"effort: {mapping['effort']}")
    if meta.get("tools"):
        lines.append(f"tools: {meta['tools']}")
    return _markdown(lines, meta, body)


def _render_cursor(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the Cursor copy: model ``[effort=…]``, read-only flag."""
    lines = [f"name: {meta['name']}"]
    lines.append(f"description: {_quote(meta['description'])}")
    if mapping.get("model"):
        model = mapping["model"]
        if mapping.get("effort"):
            model += f"[effort={mapping['effort']}]"
        lines.append(f"model: {_quote(model)}")
    if _is_readonly(meta):
        lines.append("readonly: true")
    return _markdown(lines, meta, body)


def _render_gemini(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the Gemini CLI copy; tools are inherited (names differ)."""
    lines = [f"name: {meta['name']}"]
    lines.append(f"description: {_quote(meta['description'])}")
    if mapping.get("model"):
        lines.append(f"model: {_quote(mapping['model'])}")
    return _markdown(lines, meta, body)


def _render_opencode(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the OpenCode copy: ``mode: subagent``, edit permission."""
    lines = [f"description: {_quote(meta['description'])}", "mode: subagent"]
    if mapping.get("model"):
        lines.append(f"model: {_quote(mapping['model'])}")
    if _is_readonly(meta):
        lines += ["permission:", "  edit: deny"]
    return _markdown(lines, meta, body)


def _render_copilot(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the VS Code / GitHub Copilot copy (``.agent.md``)."""
    lines = [f"name: {meta['name']}"]
    lines.append(f"description: {_quote(meta['description'])}")
    if mapping.get("model"):
        lines.append(f"model: {_quote(mapping['model'])}")
    return _markdown(lines, meta, body)


def _render_codex(meta: Dict[str, str], body: str, mapping: dict) -> str:
    """Return the Codex copy: TOML, instructions as a literal string.

    Raises:
        click.ClickException: if the body contains ``'''``, which a TOML
            literal string cannot hold.
    """
    if "'''" in body:
        message = f"{meta['name']}: the instructions contain ''' (TOML)"
        raise click.ClickException(message)
    lines = [
        (
            f"# {GENERATED_MARK} from {AGENTS_DIR.as_posix()}/"
            f"{meta['name']}.md (tier {meta['tier']}); edit that"
        ),
        f"name = {_quote(meta['name'])}",
        f"description = {_quote(meta['description'])}",
    ]
    if mapping.get("model"):
        lines.append(f"model = {_quote(mapping['model'])}")
    if mapping.get("effort"):
        lines.append(f"model_reasoning_effort = {_quote(mapping['effort'])}")
    lines.append(f"developer_instructions = '''\n{body.strip()}\n'''")
    return "\n".join(lines) + "\n"


# Where each harness reads project subagents (relative to the workspace
# root), the file name pattern, and the writer of its format.
HARNESSES = {
    "claude": (Path(".claude") / "agents", "{}.md", _render_claude),
    "cursor": (Path(".cursor") / "agents", "{}.md", _render_cursor),
    "codex": (Path(".codex") / "agents", "{}.toml", _render_codex),
    "gemini": (Path(".gemini") / "agents", "{}.md", _render_gemini),
    "opencode": (Path(".opencode") / "agents", "{}.md", _render_opencode),
    "copilot": (Path(".github") / "agents", "{}.agent.md", _render_copilot),
}


def load_config(root: Path) -> dict:
    """Load ``.agents/tiers.json`` over the built-in defaults.

    Args:
        root (Path): resolved workspace root.

    Returns:
        dict: ``targets`` (harnesses to write for), ``tiers`` and
            ``harnesses`` (tier -> model and effort, per harness).
    """
    path = root / TIERS_FILE
    override = json.loads(path.read_text()) if path.is_file() else {}
    return _merge(DEFAULTS, override)


def resolve_harnesses(harness: str, config: dict) -> List[str]:
    """Return the harnesses to act on: ``harness`` or every target.

    Args:
        harness (str): one harness name; empty means ``targets``.
        config (dict): result of ``load_config``.

    Returns:
        List[str]: known harness names.

    Raises:
        click.ClickException: if a name has no writer in ``HARNESSES``.
    """
    names = [harness] if harness else list(config["targets"])
    unknown = [name for name in names if name not in HARNESSES]
    if unknown:
        message = (
            f"No writer for harness {', '.join(unknown)} — known: "
            f"{', '.join(HARNESSES)} (add one in workspace_agents.py)."
        )
        raise click.ClickException(message)
    return names


def resolve_tier(tier: str, harness: str, config: dict) -> Dict[str, str]:
    """Return the model and effort a tier gets on a harness.

    Args:
        tier (str): ``light``, ``standard`` or ``deep``.
        harness (str): harness name, a key of ``HARNESSES``.
        config (dict): result of ``load_config``.

    Returns:
        Dict[str, str]: ``harness``, ``tier`` and, where mapped, ``model``
            and ``effort``; without a model the harness inherits the
            delegating session's model.

    Raises:
        click.ClickException: if the tier is not one of ``tiers``.
    """
    if tier not in config["tiers"]:
        message = (
            f"Unknown tier '{tier}' — use one of "
            f"{', '.join(config['tiers'])} ({TIERS_FILE})."
        )
        raise click.ClickException(message)
    mapping = config["harnesses"].get(harness, {}).get(tier, {})
    return {"harness": harness, "tier": tier, **mapping}


def read_definitions(root: Path) -> List[Tuple[Dict[str, str], str]]:
    """Read every definition in ``.agents/agents/``, sorted by file name.

    Args:
        root (Path): resolved workspace root.

    Returns:
        List[Tuple[Dict[str, str], str]]: frontmatter fields and body of
            each definition.

    Raises:
        click.ClickException: if a definition has no frontmatter, or lacks
            ``name``, ``description`` or ``tier``.
    """
    definitions = []
    for path in sorted((root / AGENTS_DIR).glob("*.md")):
        match = FRONTMATTER.match(path.read_text())
        if not match:
            message = f"{path} has no frontmatter"
            raise click.ClickException(message)
        meta = {}
        for line in match.group(1).splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip()
        missing = {"name", "description", "tier"} - set(meta)
        if missing:
            message = f"{path} lacks {', '.join(sorted(missing))}"
            raise click.ClickException(message)
        definitions.append((meta, match.group(2)))
    return definitions


def plan_sync(
    root: Path, harness: str, config: dict
) -> Tuple[Dict[Path, str], List[Path]]:
    """Return what ``sync`` would change for one harness, writing nothing.

    Args:
        root (Path): resolved workspace root.
        harness (str): harness name, a key of ``HARNESSES``.
        config (dict): result of ``load_config``.

    Returns:
        Tuple[Dict[Path, str], List[Path]]: files to write (missing or out
            of date) with their content, and generated files whose
            definition is gone.
    """
    out_dir, pattern, render = HARNESSES[harness]
    out_dir = root / out_dir
    writes = {}
    expected = set()
    for meta, body in read_definitions(root):
        dest = out_dir / pattern.format(meta["name"])
        expected.add(dest)
        mapping = resolve_tier(meta["tier"], harness, config)
        text = render(meta, body, mapping)
        if not dest.is_file() or dest.read_text() != text:
            writes[dest] = text
    stale = [
        path
        for path in sorted(out_dir.glob("*"))
        if path.is_file()
        and path not in expected
        and GENERATED_MARK in path.read_text()
    ]
    return writes, stale


def sync_agents(
    root: Path, harness: str, dry_run: bool, log: logging.Logger
) -> None:
    """Write the harness copies of every subagent; remove stale ones.

    Args:
        root (Path): resolved workspace root.
        harness (str): one harness name; empty means every target.
        dry_run (bool): if set, only log what would change.
        log (logging.Logger): logger to report progress on.
    """
    config = load_config(root)
    prefix = "[dry-run] would " if dry_run else ""
    for name in resolve_harnesses(harness, config):
        writes, stale = plan_sync(root, name, config)
        for dest, text in writes.items():
            if not dry_run:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(text)
            log.info(f"{prefix}write {dest.relative_to(root)}")
        for path in stale:
            if not dry_run:
                path.unlink()
            relative = path.relative_to(root)
            log.info(f"{prefix}remove {relative} (no definition)")
        if not writes and not stale:
            log.info(f"agents: {HARNESSES[name][0]} is up to date")


def check_agents(
    root: Path, log: logging.Logger, harness: str = ""
) -> List[str]:
    """Return drift messages for the harness copies (``doctor``).

    Args:
        root (Path): resolved workspace root.
        log (logging.Logger): logger for informational notes.
        harness (str): one harness name; empty means every target.

    Returns:
        List[str]: one message per file ``sync`` would change; empty means
            clean.
    """
    fix = "run `uv run ayon-workspace agents sync`"
    problems = []
    try:
        config = load_config(root)
        for name in resolve_harnesses(harness, config):
            writes, stale = plan_sync(root, name, config)
            problems += [
                f"{dest.relative_to(root)} is missing or out of date — {fix}"
                for dest in writes
            ]
            problems += [
                f"{path.relative_to(root)} has no definition left — {fix}"
                for path in stale
            ]
            if not writes and not stale:
                log.info(f"agents: {HARNESSES[name][0]} matches {AGENTS_DIR}")
    except click.ClickException as exc:
        problems.append(f"agents: {exc.message}")
    return problems


harness_option = click.option(
    "--harness",
    default="",
    help="One harness (default: every target in .agents/tiers.json).",
)


@click.group(name="agents")
def agents() -> None:
    """Universal .agents/ subagents and their tiers (docs/subagents.md)."""


@agents.command(name="list")
@harness_option
def list_agents(harness: str) -> None:
    """Show each definition with its tier and model on each harness."""
    root = resolve_workspace_root()
    config = load_config(root)
    names = resolve_harnesses(harness, config)
    header = "".join(f"{name:<18}" for name in names)
    click.echo(f"{'agent':<20}{'tier':<10}{header}")
    for meta, _body in read_definitions(root):
        cells = []
        for name in names:
            mapping = resolve_tier(meta["tier"], name, config)
            model = mapping.get("model", "inherit")
            if mapping.get("effort"):
                model += f"/{mapping['effort']}"
            cells.append(f"{model:<18}")
        click.echo(f"{meta['name']:<20}{meta['tier']:<10}{''.join(cells)}")


@agents.command(name="tier")
@click.argument("tier_name", metavar="TIER")
@harness_option
def tier(tier_name: str, harness: str) -> None:
    """Print the model and effort of TIER as JSON, one line per harness."""
    config = load_config(resolve_workspace_root())
    for name in resolve_harnesses(harness, config):
        click.echo(json.dumps(resolve_tier(tier_name, name, config)))


@agents.command(name="sync")
@click.option(
    "--check", is_flag=True, help="Only report drift; exit 1 if there is any."
)
@harness_option
def sync(check: bool, harness: str) -> None:
    """Write each harness's copy of the subagents in .agents/agents/.

    Raises:
        SystemExit: with code 1 if ``--check`` finds drift.
    """
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    log = logging.getLogger("agents")

    root = resolve_workspace_root()
    if not check:
        sync_agents(root, harness, dry_run=False, log=log)
        return

    problems = check_agents(root, log, harness)
    for problem in problems:
        log.info(problem)
    if problems:
        raise SystemExit(1)


if __name__ == "__main__":
    agents()
